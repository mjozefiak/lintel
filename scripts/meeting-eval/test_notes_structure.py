import contextlib
import io
import os
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import notes_structure as tool  # noqa: E402


def topic(name, count):
    return "### %s\n%s\n" % (name, "\n".join("- point %d of %s." % (i, name) for i in range(count)))


GOOD_PL = (
    "Zespół omówił zmianę kuriera. Ustalono plan na tydzień.\n\n"
    + topic("Opóźnienia", 3)
    + "\n"
    + topic("Koszty", 2)
    + "\n### Podjęte decyzje\n- Zwykłe paczki idą nowym kurierem.\n\n"
    + "### Następne kroki\n- [ ] Ustawić kuriera — osoba: Julia, termin: piątek\n\n### Uczestnicy\nHanna, Bartek\n"
)


def result(markdown, minutes=30, lang="pl", **kwargs):
    return tool.analyse(markdown, minutes, lang, **kwargs)


def failed(res):
    return sorted(r["rule"] for r in res["rules"] if not r["pass"])


class MaxTopicsTests(unittest.TestCase):
    def test_table_from_the_spec(self):
        self.assertEqual([tool.max_topics(m) for m in (10, 12, 24, 38, 55, 60, 180)], [2, 2, 4, 6, 9, 10, 10])


class StructureTests(unittest.TestCase):
    def test_a_conforming_note(self):
        # two topics, 5 points in all: short by the points rule, so no topic headings are expected
        res = result(GOOD_PL, expect_decisions=True, expect_next_steps=True)
        self.assertTrue(res["short_meeting"])
        full = (
            "Zespół omówił zmianę kuriera.\n\n" + topic("A", 3) + topic("B", 3) + topic("C", 2)
            + "### Podjęte decyzje\n- Zwykłe paczki idą nowym kurierem.\n\n"
            + "### Następne kroki\n- [ ] Ustawić kuriera — osoba: Julia\n\n### Uczestnicy\nHanna, Bartek\n"
        )
        res = result(full, minutes=48, expect_decisions=True, expect_next_steps=True)
        self.assertEqual(failed(res), [])
        self.assertEqual((res["layout"], res["topics"], res["max_topics"]), ("topics", 3, 8))

    def test_too_many_topics_and_points(self):
        many = "".join(topic("T%d" % i, 2) for i in range(7))
        self.assertEqual(failed(result(many, minutes=24)), ["topics_within_max"])
        self.assertEqual(failed(result(topic("A", 7) + topic("B", 3) + topic("C", 3), minutes=40)), ["points_per_topic"])
        self.assertEqual(failed(result(topic("A", 1) + topic("B", 3) + topic("C", 3), minutes=40)), ["points_per_topic"])

    def test_other_may_have_one_point(self):
        res = result(topic("A", 3) + topic("B", 3) + topic("Inne", 1), minutes=40)
        self.assertEqual(failed(res), [])

    def test_other_comes_on_top_of_the_limit(self):
        # 38 minutes: limit 6; six named topics plus "Other" is conforming.
        res = result("".join(topic("T%d" % i, 2) for i in range(6)) + topic("Inne", 2), minutes=38)
        self.assertEqual(failed(res), [])

    def test_a_long_meeting_cannot_be_one_flat_list(self):
        flat = "Intro.\n\n" + "".join("- point %d.\n" % i for i in range(20))
        self.assertEqual(failed(result(flat, minutes=40)), ["no_headingless_points"])

    def test_a_short_meeting_has_no_topic_headings(self):
        flat = "Krótka rozmowa o kurierze.\n\n- one.\n- two.\n- three.\n"
        self.assertEqual(failed(result(flat, minutes=8)), [])
        self.assertEqual(failed(result(topic("A", 2) + topic("B", 2), minutes=8)), ["topics_within_max"])

    def test_sections_expected_but_missing(self):
        res = result(topic("A", 3) + topic("B", 3), minutes=30, expect_decisions=True, expect_next_steps=True)
        self.assertEqual(failed(res), ["decisions_section", "next_steps_section"])

    def test_times_and_author_marks(self):
        for text in ("Point [12:34] here.", "Point ~12:34 here.", "Point (12:34)"):
            self.assertIn("no_times", failed(result(topic("A", 3) + text, minutes=30)))
        # a clock hour in a sentence is a fact
        self.assertNotIn("no_times", failed(result(topic("A", 3) + "Spotkanie o 17:00.", minutes=30)))
        for text in ("Generated by Acme AI", "Wygenerowane przez AI", "🤖"):
            self.assertIn("no_author_marks", failed(result(topic("A", 3) + text, minutes=30)))

    def test_labels_follow_the_language(self):
        english = "### Decisions\n- a.\n\n### Next steps\n- [ ] b\n"
        self.assertIn("labels_in_language", failed(result(topic("A", 3) + english, lang="pl")))
        self.assertNotIn("labels_in_language", failed(result(topic("A", 3) + english, lang="en")))
        self.assertIn("labels_in_language", failed(result(topic("A", 3) + GOOD_PL, lang="en")))

    def test_unassigned_label(self):
        text = topic("A", 3) + "### Next steps\n- [ ] Do it — owner: Unassigned\n"
        self.assertIn("no_unassigned_label", failed(result(text, lang="en")))
        pl = topic("A", 3) + "### Następne kroki\n- [ ] Zrób — osoba: Do przypisania\n"
        self.assertIn("no_unassigned_label", failed(result(pl)))

    def test_intro_length(self):
        long_intro = "One. Two. Three. Four.\n\n" + topic("A", 3)
        self.assertIn("intro_short", failed(result(long_intro, minutes=30, lang="en")))
        wordy = " ".join(["word"] * 71) + ".\n\n" + topic("A", 3)
        self.assertIn("intro_short", failed(result(wordy, minutes=30, lang="en")))
        self.assertNotIn("intro_short", failed(result("One. Two. Three.\n\n" + topic("A", 3), lang="en")))

    def test_the_old_layout_is_recognised_and_fails_the_new_rules(self):
        old = "## Podsumowanie\n\n" + " ".join(["Zdanie."] * 5) + "\n\n## Omówione tematy\n\n- a.\n- b.\n"
        res = result(old, minutes=30)
        self.assertEqual(res["layout"], "old")
        self.assertIn("intro_short", failed(res))


class CommandLineTests(unittest.TestCase):
    def run_cli(self, markdown, *args):
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "n.md")
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(markdown)
            out = io.StringIO()
            with contextlib.redirect_stdout(out):
                code = tool.main(["--notes", path, *args])
        return code, out.getvalue()

    def test_exit_codes_and_no_text_in_the_output(self):
        secret = "UnikalnaFrazaKurierska"
        code, text = self.run_cli(topic(secret, 3) + topic("B", 3) + topic("C", 3), "--duration-min", "40", "--lang", "pl")
        self.assertEqual(code, 0)
        self.assertNotIn(secret, text)
        self.assertIn("conforms=true", text)
        code, text = self.run_cli("Point [01:02].\n", "--duration-min", "40", "--lang", "pl")
        self.assertEqual(code, 1)
        self.assertIn("FAIL no_times", text)
        self.assertEqual(tool.main(["--notes", "/nonexistent.md", "--duration-min", "5", "--lang", "en"]), 2)
        self.assertEqual(self.run_cli("x", "--duration-min", "0", "--lang", "en")[0], 2)


if __name__ == "__main__":
    unittest.main()
